// Turns the card takes (raw/tiles/*.json, from record-tiles.mjs) into Remotion scenes: each clip runs from
// mark `a` to mark `b`, zoomed onto the part of the screen it is about (a card is small, the whole 1440 px
// screen would be unreadable). Copies the takes, logs and first frames into public/.
// usage: node make-tiles.mjs   → src/scenes/tiles.generated.js
import {readFileSync, writeFileSync, copyFileSync, existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';

// Where the camera looks (CSS px of the 1440×900 demo) and how close; `cursor: false` for map-only shots.
export const FOCUS = {
  today: {x: 1060, y: 380, s: 1.6},
  occupancy: {x: 520, y: 400, s: 1.4},
  inventory: {x: 480, y: 320, s: 1.5},
  fleet: {x: 1000, y: 380, s: 1.5},
  history: {x: 480, y: 320, s: 1.5},
  move: {x: 860, y: 450, s: 1.4},
  editor: {x: 720, y: 460, s: 1.15},
  zone: {x: 900, y: 420, s: 1.3},
  another: {x: 720, y: 450, s: 1.7},
  big: {x: 720, y: 450, s: 1.7},
  product: {x: 720, y: 450, s: 1.7},
  lanes: {x: 720, y: 450, s: 1, cursor: false},
  conveyor: {x: 720, y: 450, s: 1, cursor: false},
  parking: {x: 720, y: 450, s: 1, cursor: false},
  charging: {x: 720, y: 450, s: 1, cursor: false},
};

const scenes = {};
for (const [name, f] of Object.entries(FOCUS)) {
  const json = `raw/tiles/${name}.json`;
  if (!existsSync(json)) { console.log('skip', name); continue; }
  const {marks} = JSON.parse(readFileSync(json, 'utf8'));
  if (marks.a == null || marks.b == null) { console.log('no marks', name); continue; }
  const from = Math.max(0, marks.a - 0.1), to = marks.b;
  copyFileSync(`raw/tiles/${name}.mp4`, `public/tile-${name}.mp4`);
  copyFileSync(json, `public/tile-${name}.json`);
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-ss', String(from), '-i', `raw/tiles/${name}.mp4`, '-frames:v', '1', `public/tile-${name}-first.png`]);
  scenes[name] = {
    video: `tile-${name}.mp4`, log: `tile-${name}.json`, first: `tile-${name}-first.png`,
    segments: [{from, to, rate: 1}],
    camera: [{t: from, s: f.s, x: f.x, y: f.y}],
    cursorUntil: f.cursor === false ? 0 : to + 1,
    loopFade: 0.4,
  };
  console.log(name, from.toFixed(2), '→', to.toFixed(2), `(${(to - from).toFixed(1)} s)`);
}
writeFileSync('src/scenes/tiles.generated.js',
  `// Generated by make-tiles.mjs from raw/tiles/*.json — do not edit by hand.\nexport default ${JSON.stringify(scenes, null, 1)};\n`);
